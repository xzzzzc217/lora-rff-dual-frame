# ---- 批注1 (para 77) : 集成后验概率公式参数解释 ----
# 上文："对4个分类器输出的后验概率按联合权重加权求和，得到集成后验概率："
# 公式：P(y=c|F) = Σ α_k · P_k(y=c|F)
append_text(paras[77],
    "其中，F 为当前待识别样本的特征向量；c 为候选设备类别标识，取值范围为 {1, 2, …, C}，"
    "C 为训练集中的设备总数；K 为基础分类器的个数（本实施例中 K=4，分别为 SVM、"
    "随机森林、LDA 和 KNN）；α_k 为第 k 个分类器的联合权重，满足 Σα_k=1；"
    "P_k(y=c|F) 为第 k 个分类器对样本 F 属于类别 c 的后验概率估计；"
    "P(y=c|F) 为集成后的后验概率。"
)

# ---- 批注2 (para 89) : 静态基权重 α_k^0 = A_k / Σ A_j ----
# 原文以逗号结尾："...表示第j个分类器单独的识别准确率， "
append_text(paras[89],
    "K 为基础分类器的总数；A_k 为第 k 个分类器在验证集上的识别准确率，"
    "取值范围为 [0, 1]；分母 Σ_{j=1}^{K} A_j 用于归一化，"
    "使得所有分类器的静态基权重之和为 1，即 Σ_{k=1}^{K} α_k^0 = 1。"
    "静态基权重 α_k^0 越大，表示该分类器在验证集上的整体判别能力越强。"
)

# ---- 批注3 (para 98) : 联合权重 α_k = (α_k^0 · β_k) / Σ(...) ----
# 原文："联合权重  同时考虑了分类器的历史准确率（静态稳健性）与当前样本的预测确定性（动态置信度）..."
append_text(paras[98],
    "其中，α_k^0 为第 k 个分类器的静态基权重（由验证集准确率确定）；"
    "β_k = exp(-γ·H_k) 为第 k 个分类器针对当前样本的动态置信因子，"
    "H_k 为该分类器输出后验概率向量的信息熵（熵值越小表明预测越确定），"
    "γ > 0 为温度超参数（本实施例取 γ=1.0）用于控制熵对权重的调节强度；"
    "分母为归一化项，确保 Σ_{k=1}^{K} α_k = 1。"
)

# ---- 批注4 (para 102) : 类间置信差 Δ = P(1) - P(2) ----
# 原文："类间置信差  度量最优类别相对于次优类别的置信优势，反映识别结果的区分度，"
append_text(paras[102],
    "其中，P_(1) 为集成后验概率向量 {P(y=c|F)}_{c=1}^{C} 中的最大值，"
    "对应最可能的设备类别；P_(2) 为该向量中的次大值，对应次可能类别；"
    "Δ = P_(1) − P_(2) ∈ [0, 1]，Δ 值越大表明最优类别与次优类别的区分越显著、"
    "识别结果越可靠；Δ 值越小则表明分类器对当前样本存在较强的类别混淆，"
    "该样本更可能属于未知设备或非法接入。"
)

# ---- 批注9 (para 210) : 帧起始位置 n̂ ----
# 原文："其中  为检测得到的帧起始位置。"
append_text(paras[210],
    "具体而言，n̂ 为通过 Schmidl-Cox 相关检测算法在连续 I/Q 数据流中定位得到的 LoRa 帧"
    "前导码起始采样点索引，r[n] 为原始接收信号的第 n 个采样点，"
    "s[n] 为截取得到的同步后信号（包含完整前导码部分），n 的取值范围为 [0, N−1]，"
    "N 为单帧信号的总采样点数（由前导码长度和采样率共同决定）。"
)

# ---- 批注10 (para 214) : 载波频偏估计公式参数 ----
# 上文："...通过分析相邻采样点之间的相位变化估计载波频偏，其表达式为："
# 公式：ε̂ = 1/(2πT) · angle( Σ r*[n]·r[n+1] )
# 原文："其中 T 为采样周期。"
append_text(paras[214],
    "具体而言，ε̂ 为估计得到的载波频偏（单位：Hz）；"
    "T = 1/f_s 为采样周期，f_s 为接收机采样率；"
    "r[n] 为同步后信号的第 n 个复数采样点，r*[n] 为其共轭；"
    "angle(·) 表示取复数的相位角（取值范围 (−π, π]）；"
    "求和范围覆盖用于估计的相邻采样点对，通过对多个相位差的相干累加抑制噪声影响，"
    "从而得到更稳健的频偏估计。"
)

